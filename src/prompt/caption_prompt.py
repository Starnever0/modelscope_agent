def build_caption_prompt(alt_text: str = "", context_text: str = "") -> str:
    alt = (alt_text or "").strip() or "无"
    context = (context_text or "").strip() or "无"

    return (
        "你是一个擅长从技术文档配图中提取信息的 AI 助手。\n"
        "核心任务：读取并提炼图片里的实际信息，而不是只描述外观。\n\n"
        "请按以下优先级理解图片：\n"
        "1. 文档截图/界面截图（最常见）：提取关键文字、按钮名、字段名、参数名、菜单路径、提示信息。\n"
        "2. 操作流程图：提取步骤顺序、前置条件、分支条件、输入输出。\n"
        "3. 架构图/关系图：提取组件名称、连接关系、数据或控制流向。\n"
        "4. 图表：提取关键数值、趋势结论、对比对象。\n\n"
        "结合【上下文片段】生成 1 句中文描述（30-100 字），用于检索召回。\n"
        "输出要求：\n"
        "- 必须包含 2-4 个可检索关键词（如界面名称、模型名、功能名、参数名、操作动作）。\n"
        "- 尽量保留原词（按钮名/字段名/参数名），不要泛化成“某按钮”“某参数”。\n"
        "- 信息不足时使用“文档配图，展示相关操作界面/流程”这类保守表述，不得臆测。\n"
        "- 禁止输出“这是一张截图/图片”这类无信息废话。\n"
        "- 只输出纯文本一句话，不要 Markdown、编号、前后解释。\n\n"
        f"【图片 alt】{alt}\n"
        f"【上下文片段】{context}"
    )
